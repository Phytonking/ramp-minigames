const SPEND_SORT_CODE = `"use client";
import { useState, useEffect, useCallback } from "react";

type Tier = 0 | 1 | 2;
type Task = { id: number; label: string; tier: Tier; born: number };

const TIERS = ["Cheap / Fast", "Balanced", "Expensive"];
const FEED = ["OCR a receipt", "Draft a memo", "Reconcile ledger", "Classify txn"];

// Generated by Cursor from the Ramp "third pillar" funding announcement.
export default function SpendSort({ onComplete }: GameProps) {
  const [queue, setQueue] = useState<Task[]>([]);
  const [budget, setBudget] = useState(100);
  const [score, setScore] = useState(0);

  const spawn = useCallback(() => {
    const tier = Math.floor(Math.random() * 3) as Tier;
    setQueue((q) => [...q, { id: Date.now(), label: FEED[tier], tier, born: Date.now() }]);
  }, []);

  useEffect(() => {
    const rate = Math.max(400, 1200 - score * 20);
    const t = setInterval(spawn, rate);
    return () => clearInterval(t);
  }, [spawn, score]);

  const route = (task: Task, bucket: Tier) => {
    const correct = task.tier === bucket;
    setBudget((b) => b - (correct ? 2 : 6));
    setScore((s) => s + (correct ? 1 : 0));
    setQueue((q) => q.filter((t) => t.id !== task.id));
  };

  useEffect(() => {
    if (budget <= 0) {
      const saved = Math.round(60 + score * 0.4);
      onComplete({ score, stat: \`Saved \${saved}% vs. all-expensive routing\` });
    }
  }, [budget, score, onComplete]);

  return (
    <div className="grid gap-4 font-sans">
      <BudgetBar value={budget} score={score} />
      <TaskQueue tasks={queue} tiers={TIERS} onRoute={route} />
    </div>
  );
}
`;

const TRIAGE_CODE = `"use client";
import { useState, useEffect, useRef } from "react";

type Kind = "routine" | "judgment";
type Request = { id: number; vendor: string; amount: number; kind: Kind };

const VENDORS = ["Notion", "AWS", "Ramp Travel", "Figma", "Anthropic"];

// Generated by Cursor from the "AI agents for procurement" launch.
export default function Triage({ onComplete }: GameProps) {
  const [queue, setQueue] = useState<Request[]>([]);
  const [reviewed, setReviewed] = useState(0);
  const [autoHandled, setAutoHandled] = useState(0);
  const clock = useRef(30);

  useEffect(() => {
    const t = setInterval(() => {
      const kind: Kind = Math.random() > 0.55 ? "routine" : "judgment";
      setQueue((q) => [...q, {
        id: Date.now(),
        vendor: VENDORS[Math.floor(Math.random() * VENDORS.length)],
        amount: Math.round(Math.random() * 4000),
        kind,
      }]);
    }, 900);
    return () => clearInterval(t);
  }, []);

  // The agent clears routine requests so the human only sees judgment calls.
  useEffect(() => {
    const auto = setInterval(() => {
      setQueue((q) => {
        const routine = q.filter((r) => r.kind === "routine");
        if (routine.length) setAutoHandled((n) => n + 1);
        return q.filter((r) => r.kind !== "routine");
      });
    }, 2000);
    return () => clearInterval(auto);
  }, []);

  const decide = (id: number) => {
    setReviewed((n) => n + 1);
    setQueue((q) => q.filter((r) => r.id !== id));
  };

  return <TriageBoard queue={queue} onDecide={decide} clock={clock.current} />;
}
`;

const THEN_VS_NOW_CODE = `"use client";
import { useState, useRef } from "react";

type Round = "manual" | "auto";
type Receipt = { id: number; merchant: string; category: string };

const RECEIPTS: Receipt[] = seedReceipts(8);

// Generated by Cursor from the original receipt-automation product page.
export default function ThenVsNow({ onComplete }: GameProps) {
  const [round, setRound] = useState<Round>("manual");
  const [index, setIndex] = useState(0);
  const start = useRef(performance.now());
  const manualMs = useRef(0);

  const submit = (typed: string) => {
    const r = RECEIPTS[index];
    const ok = round === "auto" || typed.trim() === r.category;
    if (!ok) return;
    if (index + 1 < RECEIPTS.length) {
      setIndex((i) => i + 1);
      return;
    }
    const elapsed = performance.now() - start.current;
    if (round === "manual") {
      manualMs.current = elapsed;
      setRound("auto");
      setIndex(0);
      start.current = performance.now();
    } else {
      const m = Math.floor(manualMs.current / 60000);
      const s = Math.round((manualMs.current % 60000) / 1000);
      onComplete({
        score: Math.round(manualMs.current / elapsed),
        stat: \`Manual: \${m}m \${s}s · Automated: \${(elapsed / 1000).toFixed(1)}s\`,
      });
    }
  };

  return <RaceBoard round={round} receipt={RECEIPTS[index]} onSubmit={submit} />;
}
`;

