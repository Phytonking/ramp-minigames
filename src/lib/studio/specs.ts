/** Match a pasted excerpt / URL to the best sample; falls back to the first. */
export function findSampleForInput(input: string): SampleSpec {
  const text = input.trim().toLowerCase();
  if (!text) return SAMPLE_SPECS[0];
  const scored = SAMPLE_SPECS.map((s) => {
    const haystack = `${s.report} ${s.excerpt} ${s.slug}`.toLowerCase();
    let score = 0;
    if (haystack.includes(text) || text.includes(s.excerpt.toLowerCase())) score += 100;
    for (const word of text.split(/\s+/)) {
      if (word.length > 3 && haystack.includes(word)) score += 1;
    }
    return { s, score };
  });
  scored.sort((a, b) => b.score - a.score);
  return scored[0].score > 0 ? scored[0].s : SAMPLE_SPECS[0];
}
